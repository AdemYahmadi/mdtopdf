#!/usr/bin/env node
"use strict";

// Workers have no project filesystem, so bake the CSS that mdtohtml.js
// normally reads from node_modules into a module the Worker can import.

const fs = require("fs");
const path = require("path");
const { nodeAssetLoader, THEMES } = require("../mdtohtml");

const hljs = {};
for (const t of Object.values(THEMES)) hljs[t.file] = nodeAssetLoader.hljsCss(t.file);

const out = `// Generated by scripts/build-worker-assets.js. Do not edit.
export const katexCss = ${JSON.stringify(nodeAssetLoader.katexCss())};
export const hljsCss = ${JSON.stringify(hljs)};
`;

const outPath = path.join(__dirname, "..", "worker", "assets.generated.js");
fs.writeFileSync(outPath, out, "utf8");
console.log(`wrote ${path.relative(process.cwd(), outPath)} (${out.length} bytes)`);
